# Regenerates src/lmu/layout.rs from the headers Le Mans Ultimate installs.
#
# Run this after a game update, or when `probe` reports a different memory size. It needs the game and the
# Visual Studio C++ Build Tools. It compiles tools/layout_check.cpp against the game's own headers on this
# machine and writes only numbers (sizes and offsets). The headers are never copied into the repository:
# their licence does not allow redistributing them.
#
#   pwsh xpeed-sim/tools/regen-layout.ps1 -GameDir 'F:\SteamLibrary\steamapps\common\Le Mans Ultimate'

param(
    [Parameter(Mandatory = $true)][string]$GameDir,
    [string]$VcVars = 'C:\Program Files (x86)\Microsoft Visual Studio\2022\BuildTools\VC\Auxiliary\Build\vcvars64.bat'
)

$ErrorActionPreference = 'Stop'
$headers = Join-Path $GameDir 'Support\SharedMemoryInterface'
if (-not (Test-Path (Join-Path $headers 'SharedMemoryInterface.hpp'))) { throw "No SharedMemoryInterface.hpp in $headers" }
if (-not (Test-Path $VcVars)) { throw "vcvars64.bat not found at $VcVars" }

$tools = Join-Path $PSScriptRoot '.'
$work = Join-Path ([IO.Path]::GetTempPath()) 'xpeed-layout-check'
New-Item -ItemType Directory -Force $work | Out-Null
Copy-Item (Join-Path $tools 'layout_check.cpp') $work -Force

$build = Join-Path $work 'build.bat'
@"
@echo off
call "$VcVars" >nul 2>nul
cd /d "$work"
cl /nologo /std:c++17 /EHsc /W0 /I"$headers" layout_check.cpp /Fe:layout_check.exe
"@ | Set-Content -Encoding ASCII $build
cmd /c "`"$build`"" | Out-Null
$exe = Join-Path $work 'layout_check.exe'
if (-not (Test-Path $exe)) { throw 'The layout checker did not compile.' }

$numbers = & $exe | Where-Object { $_ -notmatch '^// Generated by' }
$version = (Get-Item (Join-Path $GameDir 'Le Mans Ultimate.exe')).VersionInfo.ProductVersion
$header = @"
//! Where each field Xpeed Sim reads sits in the memory Le Mans Ultimate shares (``LMU_Data``).
//!
//! GENERATED: do not edit by hand. These are numbers only (sizes and byte offsets), produced by
//! ``tools/layout_check.cpp``, a small helper compiled against the headers the game installs in
//! ``Support\SharedMemoryInterface`` (see ``tools/regen-layout.ps1``). The headers themselves are not
//! part of this repository: their licence does not allow redistributing them.
//!
//! Generated for LMU $version. If the game changes the layout, regenerate this file and check
//! ``LAYOUT_SIZE`` against the size Xpeed Sim reports in ``probe``.
#![allow(dead_code)]

"@
$target = Join-Path $PSScriptRoot '..\src\lmu\layout.rs'
((($header -split "`r?`n") + $numbers) -join "`n") + "`n" | Set-Content -Encoding ASCII -NoNewline $target
"Wrote $target for LMU $version"
