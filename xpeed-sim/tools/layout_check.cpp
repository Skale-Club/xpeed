// Local-only helper: prints sizes and field offsets of the structures LMU shares, as Rust constants.
// It is compiled against the headers the game installs and is NOT part of the repository.
#include <windows.h>
#include <cstdint>
#include <cstring>
#include <utility>
#include <cstddef>
#include <cstdio>
#include "SharedMemoryInterface.hpp"

static SharedMemoryObjectOut gObj;
static const char* base() { return reinterpret_cast<const char*>(&gObj); }
#define OFF_OBJ(name, expr) std::printf("pub const %s: usize = %zu;\n", name, (size_t)(reinterpret_cast<const char*>(&(expr)) - base()))
#define OFF_IN(name, type, member) std::printf("pub const %s: usize = %zu;\n", name, offsetof(type, member))
#define SIZE(name, type) std::printf("pub const %s: usize = %zu;\n", name, sizeof(type))

int main() {
  std::printf("// Generated by a local helper compiled against the headers of LMU; numbers only.\n");
  SIZE("OBJECT_OUT_SIZE", SharedMemoryObjectOut);
  SIZE("LAYOUT_SIZE", SharedMemoryLayout);
  OFF_OBJ("GENERIC_EVENTS", gObj.generic.events);
  OFF_OBJ("GENERIC_GAME_VERSION", gObj.generic.gameVersion);
  std::printf("pub const SME_MAX: usize = %d;\n", (int)SME_MAX);
  std::printf("pub const SME_UPDATE_SCORING: u32 = %d;\n", (int)SME_UPDATE_SCORING);
  std::printf("pub const SME_UPDATE_TELEMETRY: u32 = %d;\n", (int)SME_UPDATE_TELEMETRY);
  std::printf("pub const MAX_VEHICLES: usize = %zu;\n", sizeof(gObj.scoring.vehScoringInfo) / sizeof(gObj.scoring.vehScoringInfo[0]));

  std::printf("\n// Scoring\n");
  OFF_OBJ("SCORING_INFO", gObj.scoring.scoringInfo);
  OFF_OBJ("SCORING_STREAM_SIZE", gObj.scoring.scoringStreamSize);
  OFF_OBJ("SCORING_VEHICLES", gObj.scoring.vehScoringInfo);
  SIZE("SCORING_INFO_SIZE", ScoringInfoV01);
  SIZE("VEHICLE_SCORING_SIZE", VehicleScoringInfoV01);
  OFF_IN("SI_TRACK_NAME", ScoringInfoV01, mTrackName);
  OFF_IN("SI_SESSION", ScoringInfoV01, mSession);
  OFF_IN("SI_CURRENT_ET", ScoringInfoV01, mCurrentET);
  OFF_IN("SI_LAP_DIST", ScoringInfoV01, mLapDist);
  OFF_IN("SI_NUM_VEHICLES", ScoringInfoV01, mNumVehicles);
  OFF_IN("SI_GAME_PHASE", ScoringInfoV01, mGamePhase);
  OFF_IN("SI_IN_REALTIME", ScoringInfoV01, mInRealtime);
  OFF_IN("VS_ID", VehicleScoringInfoV01, mID);
  OFF_IN("VS_DRIVER_NAME", VehicleScoringInfoV01, mDriverName);
  OFF_IN("VS_VEHICLE_NAME", VehicleScoringInfoV01, mVehicleName);
  OFF_IN("VS_TOTAL_LAPS", VehicleScoringInfoV01, mTotalLaps);
  OFF_IN("VS_FINISH_STATUS", VehicleScoringInfoV01, mFinishStatus);
  OFF_IN("VS_LAP_DIST", VehicleScoringInfoV01, mLapDist);
  OFF_IN("VS_LAST_SECTOR1", VehicleScoringInfoV01, mLastSector1);
  OFF_IN("VS_LAST_SECTOR2", VehicleScoringInfoV01, mLastSector2);
  OFF_IN("VS_LAST_LAP_TIME", VehicleScoringInfoV01, mLastLapTime);
  OFF_IN("VS_NUM_PENALTIES", VehicleScoringInfoV01, mNumPenalties);
  OFF_IN("VS_IS_PLAYER", VehicleScoringInfoV01, mIsPlayer);
  OFF_IN("VS_CONTROL", VehicleScoringInfoV01, mControl);
  OFF_IN("VS_IN_PITS", VehicleScoringInfoV01, mInPits);
  OFF_IN("VS_VEHICLE_CLASS", VehicleScoringInfoV01, mVehicleClass);
  OFF_IN("VS_LAP_START_ET", VehicleScoringInfoV01, mLapStartET);
  OFF_IN("VS_TIME_INTO_LAP", VehicleScoringInfoV01, mTimeIntoLap);
  OFF_IN("VS_COUNT_LAP_FLAG", VehicleScoringInfoV01, mCountLapFlag);

  std::printf("\n// Telemetry\n");
  OFF_OBJ("TELEMETRY_ACTIVE_VEHICLES", gObj.telemetry.activeVehicles);
  OFF_OBJ("TELEMETRY_PLAYER_INDEX", gObj.telemetry.playerVehicleIdx);
  OFF_OBJ("TELEMETRY_PLAYER_HAS_VEHICLE", gObj.telemetry.playerHasVehicle);
  OFF_OBJ("TELEMETRY_INFO", gObj.telemetry.telemInfo);
  SIZE("TELEM_INFO_SIZE", TelemInfoV01);
  SIZE("VECT3_SIZE", TelemVect3);
  OFF_IN("TI_ID", TelemInfoV01, mID);
  OFF_IN("TI_DELTA_TIME", TelemInfoV01, mDeltaTime);
  OFF_IN("TI_ELAPSED_TIME", TelemInfoV01, mElapsedTime);
  OFF_IN("TI_LAP_NUMBER", TelemInfoV01, mLapNumber);
  OFF_IN("TI_LAP_START_ET", TelemInfoV01, mLapStartET);
  OFF_IN("TI_VEHICLE_NAME", TelemInfoV01, mVehicleName);
  OFF_IN("TI_TRACK_NAME", TelemInfoV01, mTrackName);
  OFF_IN("TI_POS", TelemInfoV01, mPos);
  OFF_IN("TI_LOCAL_VEL", TelemInfoV01, mLocalVel);
  OFF_IN("TI_GEAR", TelemInfoV01, mGear);
  OFF_IN("TI_ENGINE_RPM", TelemInfoV01, mEngineRPM);
  OFF_IN("TI_THROTTLE", TelemInfoV01, mUnfilteredThrottle);
  OFF_IN("TI_BRAKE", TelemInfoV01, mUnfilteredBrake);
  OFF_IN("TI_STEERING", TelemInfoV01, mUnfilteredSteering);
  OFF_IN("TI_CLUTCH", TelemInfoV01, mUnfilteredClutch);
  OFF_IN("TI_FUEL", TelemInfoV01, mFuel);
  return 0;
}
