// Build a self-contained database seed from pinned upstream snapshots. No network is
// needed at migration time or when displaying a logo. Run explicitly to refresh it.
import { mkdir, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import sharp from 'sharp';

const sources = [
  { repo: 'filippofilip95/car-logos-dataset', revision: 'e334a4d2e8742108ba164c629dff5636576d3808' },
  { repo: 'vehiclespecs/brand-logos', revision: '3f0929e70e0a9a2a502063edc4b3e5c0146cba74' },
];
const normalize = (s) => s.normalize('NFKD').replace(/\p{M}/gu, '').toLowerCase().replace(/[^a-z0-9]/g, '');
const slug = (s) => s.normalize('NFKD').replace(/\p{M}/gu, '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const aliases = {
  volkswagen: ['VW'], 'mercedes-benz': ['Mercedes', 'Mercedes Benz'],
  chery: ['CAOA Chery'], chevrolet: ['Chevy'], ds: ['DS Automobiles'],
  'great-wall': ['Great Wall Motors', 'GWM'], 'alfa-romeo': ['Alfa Romeo Automobiles'],
  jac: ['JAC Motors'], 'rolls-royce': ['Rolls Royce'], 'land-rover': ['Landrover'],
};
const raw = (source, file) => `https://raw.githubusercontent.com/${source.repo}/${source.revision}/${file}`;
async function download(url) {
  const response = await fetch(url, { signal: AbortSignal.timeout(30_000) });
  if (!response.ok) throw new Error(`${response.status}: ${url}`);
  const bytes = Buffer.from(await response.arrayBuffer());
  if (bytes.length > 4 * 1024 * 1024) throw new Error(`Oversized source: ${url}`);
  return bytes;
}
const primary = JSON.parse((await download(raw(sources[0], 'logos/data.json'))).toString());
const secondary = JSON.parse((await download(raw(sources[1], 'brands.json'))).toString());
const candidates = new Map();
for (const brand of primary) {
  candidates.set(normalize(brand.name), {
    key: brand.slug, name: brand.name, source: sources[0],
    sourceUrl: brand.image.source, assetUrl: raw(sources[0], `logos/thumb/${brand.slug}.png`),
  });
}
for (const [name, file] of Object.entries(secondary)) {
  if (!candidates.has(normalize(name))) candidates.set(normalize(name), {
    key: slug(name), name, source: sources[1], sourceUrl: raw(sources[1], file), assetUrl: raw(sources[1], file),
  });
}
const rows = [...candidates.values()].sort((a, b) => a.key.localeCompare(b.key, 'en'));
if (new Set(rows.map((r) => r.key)).size !== rows.length) throw new Error('Duplicate brand key');
await mkdir('.codex-local/car-brands', { recursive: true });
let index = 0;
// Bounded downloads and raster decoding; SVGs never reach the browser.
await Promise.all(Array.from({ length: 6 }, async () => {
  while (index < rows.length) {
    const row = rows[index++];
    const sourceBytes = await download(row.assetUrl);
    const png = await sharp(sourceBytes, { limitInputPixels: 16_000_000 })
      .resize({ width: 256, height: 256, fit: 'inside', withoutEnlargement: true })
      .png({ compressionLevel: 9 }).toBuffer();
    row.aliases = aliases[row.key] ?? [];
    row.sourceSha256 = createHash('sha256').update(sourceBytes).digest('hex');
    row.sha256 = createHash('sha256').update(png).digest('hex');
    row.bytes = png.length;
    row.base64 = png.toString('base64');
    await writeFile(`.codex-local/car-brands/${row.key}.png`, png);
  }
}));
const quote = (s) => `'${String(s).replaceAll("'", "''")}'`;
const values = rows.map((r) => `(${[
  quote(r.key), quote(r.name), `ARRAY[${r.aliases.map(quote).join(',')}]::text[]`, quote(r.base64),
  "'image/png'", quote(r.sha256), r.bytes, quote(r.sourceUrl), quote(`${r.source.repo}@${r.source.revision}`),
].join(',')})`).join(',\n');
const sql = `-- Generated by scripts/import-car-brands.mjs. Sources and rights: docs/car-brands/README.md.
-- ${rows.length} worldwide marques, historical brands and specialist manufacturers; not an exhaustive world registry.
INSERT INTO public.car_brands (key,name,aliases,logo_base64,logo_type,logo_sha256,logo_bytes,source_url,source_revision) VALUES
${values}
ON CONFLICT (key) DO NOTHING;
`;
await writeFile('supabase/migrations/20261113070100_car_brands_seed.sql', sql);
await mkdir('docs/car-brands', { recursive: true });
await writeFile('docs/car-brands/catalog.json', JSON.stringify({ sources, count: rows.length, brands: rows.map(({ base64, source, ...row }) => ({ ...row, sourceRevision: `${source.repo}@${source.revision}` })) }, null, 2) + '\n');
console.log(`Generated ${rows.length} brands, ${rows.reduce((n, r) => n + r.bytes, 0)} PNG bytes; seed ${(sql.length / 1024 / 1024).toFixed(2)} MiB.`);
