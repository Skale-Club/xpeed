tracks AS (
  UPDATE public.sim_track_catalog c SET name = t.title
  FROM titles t
  WHERE t.kind = 'track' AND c.game = 'ac' AND c.name <> t.title
    AND public.sim_norm(c.name) = public.sim_norm(t.folder)
    AND EXISTS (SELECT 1 FROM public.sim_track_alias a
                WHERE a.game = 'ac' AND a.track_id = c.id AND a.alias_norm = left(public.sim_norm(t.folder), 160))
  RETURNING c.id
),
cars AS (
  UPDATE public.sim_car_catalog c SET name = t.title
  FROM titles t
  WHERE t.kind = 'car' AND c.game = 'ac' AND c.name <> t.title
    AND public.sim_norm(c.name) = public.sim_norm(t.folder)
    AND EXISTS (SELECT 1 FROM public.sim_car_alias a
                WHERE a.game = 'ac' AND a.car_id = c.id AND a.alias_norm = left(public.sim_norm(t.folder), 160))
  RETURNING c.id
)
SELECT (SELECT count(*) FROM tracks) AS tracks_renamed, (SELECT count(*) FROM cars) AS cars_renamed;
